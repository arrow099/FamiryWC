export function flagForTeam(team: Team): string {
  return TEAM_FLAGS_BY_ABBR[team.abbr] ?? "";
}

export function formatTeamLabel(team: Team | null | undefined, fallback = "-"): string {
  if (!team) return fallback;
  const flag = flagForTeam(team);
  return [flag, team.abbr].filter(Boolean).join(" ");
}
